create table if not exists public.patients (
    id integer generated by default as identity (start with 101) primary key,
    name varchar(50) not null,
    age integer not null check (age between 1 and 119),
    disease varchar(50) not null,
    severity integer not null check (severity between 1 and 3),
    created_at timestamptz not null default now()
);

create table if not exists public.doctors (
    id bigint generated by default as identity primary key,
    name varchar(50) not null,
    department varchar(50) not null,
    patients_treated integer not null default 0 check (patients_treated >= 0),
    unique (name, department)
);

create table if not exists public.treatment_queue (
    patient_id integer primary key references public.patients(id) on delete cascade,
    queued_at timestamptz not null default now()
);

create table if not exists public.discharge_history (
    history_id bigint generated always as identity primary key,
    patient_id integer not null,
    name varchar(50) not null,
    age integer not null,
    disease varchar(50) not null,
    severity integer not null,
    discharged_at timestamptz not null default now()
);

