create or replace function public.treat_next_patient()
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
    patient_row public.patients%rowtype;
    doctor_row public.doctors%rowtype;
    target_department text;
begin
    select p.*
    into patient_row
    from public.treatment_queue q
    join public.patients p on p.id = q.patient_id
    order by p.severity, q.queued_at, p.id
    limit 1
    for update of p;

    if not found then
        raise exception 'There are no patients waiting in the queue.';
    end if;

    target_department := case
        when lower(patient_row.disease) like '%heart%'
          or lower(patient_row.disease) like '%chest%'
          or lower(patient_row.disease) like '%bp%'
            then 'Cardiology'
        when lower(patient_row.disease) like '%fracture%'
          or lower(patient_row.disease) like '%bone%'
          or lower(patient_row.disease) like '%accident%'
            then 'Orthopedics'
        when lower(patient_row.disease) like '%skin%'
          or lower(patient_row.disease) like '%rash%'
          or lower(patient_row.disease) like '%allergy%'
            then 'Dermatology'
        else 'General Medicine'
    end;

    select d.*
    into doctor_row
    from public.doctors d
    where d.department = target_department
    order by d.patients_treated, d.id
    limit 1
    for update;

    if not found and target_department <> 'General Medicine' then
        select d.*
        into doctor_row
        from public.doctors d
        where d.department = 'General Medicine'
        order by d.patients_treated, d.id
        limit 1
        for update;
    end if;

    if not found then
        raise exception 'No doctor is available to treat this patient.';
    end if;

    update public.doctors
    set patients_treated = patients_treated + 1
    where id = doctor_row.id;

    delete from public.treatment_queue where patient_id = patient_row.id;

    return jsonb_build_object(
        'patient_id', patient_row.id,
        'patient_name', patient_row.name,
        'doctor_name', doctor_row.name,
        'department', doctor_row.department
    );
end;
$$;

create or replace function public.discharge_patient(p_patient_id integer)
returns void
language plpgsql
security invoker
set search_path = ''
as $$
declare
    patient_row public.patients%rowtype;
begin
    select p.* into patient_row
    from public.patients p
    where p.id = p_patient_id
    for update;

    if not found then
        raise exception 'Patient not found.';
    end if;

    insert into public.discharge_history (patient_id, name, age, disease, severity)
    values (patient_row.id, patient_row.name, patient_row.age, patient_row.disease, patient_row.severity);

    delete from public.treatment_queue where patient_id = patient_row.id;
    delete from public.patients where id = patient_row.id;
end;
$$;

create or replace function public.undo_last_discharge()
returns void
language plpgsql
security invoker
set search_path = ''
as $$
declare
    history_row public.discharge_history%rowtype;
begin
    select h.* into history_row
    from public.discharge_history h
    order by h.history_id desc
    limit 1
    for update;

    if not found then
        raise exception 'There is no discharge to undo.';
    end if;

    insert into public.patients (id, name, age, disease, severity)
    values (history_row.patient_id, history_row.name, history_row.age, history_row.disease, history_row.severity);

    delete from public.discharge_history where history_id = history_row.history_id;
end;
$$;

